import { expect, test } from "@playwright/test";
import { chooseToolbarOption } from "./helpers";

test.skip(!process.env.SDK_TEST_URL, "Requires the backflow-admin SDK Test server");
for (const width of [1440, 390]) {
  test(`SDK Test categories and mixed views work at ${width}px`, async ({ page }, testInfo) => {
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.setViewportSize({ width, height: 950 });
    await page.goto(process.env.SDK_TEST_URL!);
    const dataset = page.getByRole("combobox", { name: "Example dataset", exact: true });
    const category = page.getByRole("combobox", { name: "Control examples", exact: true });
    await expect(dataset).toHaveAttribute("title", "View: default");
    await expect(page.getByTestId("selected-view-label")).toHaveText("Default");
    await expect(page.getByRole("img", { name: "MCP: not connected", exact: true }).locator("strong")).toHaveCSS("font-weight", "700");
    await expect(dataset).toHaveText("");
    await expect(category).toHaveText("");
    await expect(page.getByRole("img", { name: "MCP: not connected", exact: true })).toBeVisible();
    expect(await dataset.evaluate(element => element.previousElementSibling?.getAttribute("aria-label"))).toBe("MCP: not connected");
    const topBar = page.getByRole("toolbar", { name: "Example controls", exact: true });
    await expect(topBar).toHaveCSS("border-radius", "30px");
    await expect(topBar).toHaveCSS("box-shadow", /8px/);
    const toolbarSurface = page.getByRole("toolbar", { name: "Diagram controls", exact: true }).locator('[data-flow-toolbar-scroll]').first().locator('..');
    const darkSurface = await toolbarSurface.evaluate(element => getComputedStyle(element).backgroundColor);
    await expect(topBar).toHaveCSS("background-color", darkSurface);
    const topBounds = await topBar.boundingBox();
    expect(topBounds!.x).toBeGreaterThanOrEqual(19);
    expect(Math.abs(topBounds!.x + topBounds!.width - (width - 20))).toBeLessThan(1);
    const logoBar = page.getByRole("toolbar", { name: "Logo controls", exact: true });
    await expect(logoBar).toHaveCSS("left", "20px");
    await expect(logoBar).toHaveCSS("background-color", darkSurface);
    await expect(topBar.getByRole("img", { name: "Backflow", exact: true })).toHaveCount(0);
    const logoBounds = await logoBar.boundingBox();
    expect(topBounds!.x - logoBounds!.x - logoBounds!.width).toBeGreaterThanOrEqual(23);
    await expect(logoBar.getByRole("img", { name: "Backflow", exact: true })).toBeVisible();
    expect(await logoBar.getByRole("img", { name: "Backflow", exact: true }).evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
    await page.getByTestId("theme-toggle").click();
    const lightSurface = await toolbarSurface.evaluate(element => getComputedStyle(element).backgroundColor);
    await expect(topBar).toHaveCSS("background-color", lightSurface);
    await page.getByTestId("theme-toggle").click();
      await dataset.click();
      const menu = page.getByRole("listbox", { name: "Example dataset", exact: true });
      await expect(menu.getByRole("option", { name: "default", exact: true })).toHaveAttribute("aria-selected", "true");
      const menuBounds = await menu.boundingBox();
      expect(Math.abs(menuBounds!.y - topBounds!.y - topBounds!.height - 24)).toBeLessThan(1);
      expect(menuBounds!.x).toBeGreaterThanOrEqual(12);
      expect(menuBounds!.x + menuBounds!.width).toBeLessThanOrEqual(width - 12);
      await page.screenshot({ path: testInfo.outputPath("top-dropdown.png") });
      await page.keyboard.press("Escape");
    await expect(page.getByTestId("sdk-status")).toHaveCount(0);
    await expect(page.getByTestId("sdk-log")).toHaveCount(0);
    await expect(page.locator("[data-flow-node-surface]")).toHaveCount(4);
    for (const surface of await page.locator("[data-flow-node-surface]").all()) await expect(surface).toHaveCSS("border-top-left-radius", "30px");
    await page.screenshot({ path: testInfo.outputPath("default.png") });
    await chooseToolbarOption(category, "visibility");
    await page.getByLabel("Debug status", { exact: true }).check();
    await expect(page.getByTestId("sdk-status")).toBeVisible();
    const debugPanel = page.getByTestId("sdk-debug-panel");
    await expect(debugPanel).toHaveCSS("left", "20px");
    await expect(debugPanel).toHaveCSS("background-color", darkSurface);
    await expect(topBar.getByTestId("sdk-status")).toHaveCount(0);
    await page.getByLabel("Debug status", { exact: true }).uncheck();
    await page.getByLabel("Event log", { exact: true }).check();
    await page.locator('.flow-sdk-node[data-node-id="process"]').getByText("Process", { exact: true }).click();
    await expect(page.getByTestId("sdk-log").first()).toContainText("select process");
    await page.getByLabel("Event log", { exact: true }).uncheck();
    await page.getByLabel("Default toolbar", { exact: true }).uncheck();
    await expect(page.getByRole("toolbar", { name: "Diagram controls" })).toHaveCount(0);
    await page.getByLabel("Default toolbar", { exact: true }).check();
    await chooseToolbarOption(dataset, "Mixed Views");
    await expect(page.getByTestId("selected-view-label")).toHaveText("Mixed Views");
    await expect(page.locator("[data-consumer-shape]")).toHaveCount(3);
    await expect(page.locator(".flow-sdk-node")).toHaveCount(8);
    await expect(page.locator("[data-flow-icon-label]")).toHaveCount(1);
    await chooseToolbarOption(category, "Controls");
    const closeSelection = page.getByRole("button", { name: "Close selection tools", exact: true });
    if (await closeSelection.isVisible()) await closeSelection.click();
    await page.getByRole("button", { name: "Reset zoom", exact: true }).click();
    await page.screenshot({ path: testInfo.outputPath("mixed-views.png") });
    await chooseToolbarOption(category, "primitives");
    await expect(page.getByTestId("selected-control-label")).toHaveText("Primitives");
    const panel = page.getByRole("region", { name: "SDK control examples" });
    await expect(panel).toHaveCSS("border-radius", "30px");
    await expect(panel).toHaveCSS("box-shadow", /8px/);
    await expect(panel).toHaveCSS("background-color", darkSurface);
    await page.getByTestId("theme-toggle").click();
    await expect(panel).toHaveCSS("background-color", lightSurface);
    await page.getByTestId("theme-toggle").click();
    await panel.getByRole("textbox", { name: "Example text" }).fill("Edited");
    await expect(panel.getByRole("textbox", { name: "Example text" })).toHaveCSS("border-width", "1px");
    await expect(panel.getByRole("textbox", { name: "Example text" })).toHaveCSS("border-style", "solid");
    await panel.getByRole("textbox", { name: "Example text" }).press("Enter");
    await expect(page.getByTestId("primitive-output")).toContainText("Edited");
    await page.getByRole("button", { name: "Hide example controls", exact: true }).click();
    await expect(topBar).toBeHidden();
    await expect(panel).toBeHidden();
    await expect(logoBar).toBeVisible();
    await page.getByRole("button", { name: "Show example controls", exact: true }).click();
    await expect(topBar).toBeVisible();
    await expect(panel).toBeVisible();
    await expect(dataset).toHaveAttribute("title", "View: Mixed Views");
    await expect(page.getByTestId("primitive-output")).toContainText("Edited");
    await chooseToolbarOption(category, "selection");
    await expect(panel.getByRole("textbox", { name: "Node label" })).toHaveCount(1);
    await chooseToolbarOption(category, "viewport");
    await expect(panel.getByRole("spinbutton", { name: "Focus padding" })).toHaveCSS("border-width", "1px");
    await expect(panel.getByRole("button", { name: "Focus node", exact: true })).toHaveCSS("background-color", "rgba(0, 0, 0, 0)");
    await panel.getByRole("button", { name: "Hide edges", exact: true }).click();
    await expect(page.locator(".flow-sdk-edge")).toHaveCount(0);
    await panel.getByRole("button", { name: "Show edges", exact: true }).click();
    await expect(page.locator(".flow-sdk-edge")).toHaveCount(7);
    await chooseToolbarOption(category, "provider");
    await expect(page.getByTestId("raw-provider-example").locator(".flow-sdk-node")).toHaveCount(2);
    await chooseToolbarOption(dataset, "workflow-state");
    await chooseToolbarOption(category, "forms");
    await panel.getByLabel("Workflow interface file", { exact: true }).setInputFiles("examples/workflow-state/interface.ts");
    await expect(panel.getByRole("status").filter({ hasText: "4 form types loaded" })).toBeVisible();
    await expect(panel.getByRole("combobox", { name: "Type", exact: true })).toBeVisible();
    await chooseToolbarOption(category, "appearance");
    await expect(panel.getByRole("button", { name: "Download SVG" })).toBeVisible();
    const bounds = await panel.boundingBox();
    expect(bounds!.x).toBeGreaterThanOrEqual(0);
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width);
    expect(errors).toEqual([]);
  });
}